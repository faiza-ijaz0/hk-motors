// DEMO INVENTORY — sample vehicle listings for client presentations.
//
// This is the single source of truth for demo cars. It is:
//   1. written into Supabase by `npm run seed:demo` (idempotent upsert), and
//   2. optionally served directly by `src/services/cars.ts` when
//      DEMO_DATA_FALLBACK=true and Supabase is unreachable.
//
// To replace with real stock: add real cars through /super-admin/cars, then
// run `npm run seed:demo -- --remove` to delete every demo record (all demo
// ids start with `de30`, see ./ids.ts). Real records are never touched.
//
// Photos: Unsplash (free Unsplash License), each checked by eye to match
// the listed model.

import { DEMO_TABLE, demoId, unsplash } from "./ids.ts";

type Condition = "new" | "used" | "certified_pre_owned";
type Transmission = "automatic" | "manual" | "cvt" | "dual_clutch";
type Fuel = "petrol" | "diesel" | "hybrid" | "electric" | "lpg";
type Drivetrain = "fwd" | "rwd" | "awd" | "4wd";

export type DemoMake = { id: string; name: string; slug: string };
export type DemoModel = {
  id: string;
  makeId: string;
  name: string;
  slug: string;
};
export type DemoCategory = { id: string; name: string; slug: string };
export type DemoFeature = { id: string; name: string; slug: string };

export type DemoCarImage = {
  id: string;
  url: string;
  alt: string;
};

export type DemoCar = {
  id: string;
  slug: string;
  title: string;
  makeId: string;
  modelId: string;
  categoryId: string;
  year: number;
  price: number;
  currencyCode: "PKR";
  mileage: number;
  condition: Condition;
  transmission: Transmission;
  fuelType: Fuel;
  drivetrain: Drivetrain;
  engine: string;
  horsepower: number;
  exteriorColor: string;
  interiorColor: string;
  seats: number;
  doors: number;
  isFeatured: boolean;
  viewCount: number;
  /** Days before "now" the listing was created — drives "newest" sorting. */
  listedDaysAgo: number;
  description: string;
  featureIds: string[];
  images: DemoCarImage[];
};

