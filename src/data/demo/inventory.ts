const MAKE_NAMES = [
  "Toyota",
  "Honda",
  "Suzuki",
  "Kia",
  "Hyundai",
  "Lexus",
  "Mercedes-Benz",
] as const;
type MakeName = (typeof MAKE_NAMES)[number];

function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export const demoMakes: DemoMake[] = MAKE_NAMES.map((name, i) => ({
  id: demoId(DEMO_TABLE.makes, i + 1),
  name,
  slug: slugify(name),
}));

const makeId = (name: MakeName) => demoMakes.find((m) => m.name === name)!.id;

